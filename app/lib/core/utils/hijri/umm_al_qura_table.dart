/// The reduced Julian day each month of the table starts on, and one past
/// its last month.
final List<int> monthStarts = _decode();

List<int> _decode() {
  final List<int> starts = <int>[_firstStart];
  for (final int unit in _lengths.codeUnits) {
    final int digit = unit - 48;
    starts.add(starts.last + (digit >= 8 ? 20 + digit : 30 + digit));
  }
  return starts;
}
